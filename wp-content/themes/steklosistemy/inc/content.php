function steklo_img( $file ) {
	if ( ! $file ) {
		return '';
	}
	if ( is_array( $file ) ) {
		$file = $file['url'] ?? '';
	}
	$file = (string) $file;
	if ( $file === '' ) {
		return '';
	}
	if ( preg_match( '#^(https?:)?//#i', $file ) || strpos( $file, 'data:' ) === 0 ) {
		return $file;
	}
	return get_template_directory_uri() . '/assets/img/' . ltrim( $file, '/' );
}

function steklo_page_url( $slug ) {
	$page = get_page_by_path( $slug );
	if ( $page ) {
		return get_permalink( $page );
	}
	return home_url( '/' . $slug . '/' );
}
